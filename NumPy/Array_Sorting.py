import numpy as np

arr = np.array([3, 2, 0, 1])

print(np.sort(arr))  # This method returns a copy of the array, leaving the original array unchanged.

# sort Alphabetically

arr = np.array(['banana', 'cherry', 'apple'])
print(np.sort(arr))

# Sort a Boolean Array

arr = np.array([True, False, True])
print(np.sort(arr))

