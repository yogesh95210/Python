# built in Math function
# Min and Max function

x = min(5, 10, 25,7,2)
y = max(5, 10, 25,4,89)

print(x)
print(y)

# abs function
# return absolute positive number
x = abs(-7.25)
y= abs(-1.0654)
print(x)
print(y)

# pow function
# Return the value of 4 to the power of 3 (same as 4 * 4 * 4):
x = pow(4, 3)
print(x)


# Math module

# sqrt function
import math
x = math.sqrt(64)
print(x)


# floor and ceil function


x = math.ceil(1.4)
y = math.floor(1.4)

print(x) # returns 2
print(y) # returns 1

# pi function

x = math.pi

print(x)